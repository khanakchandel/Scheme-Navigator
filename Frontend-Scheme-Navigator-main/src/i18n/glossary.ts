/**
 * Translates any phrase using the glossary with fallback
 */
export const translateGlossaryPhrase = (phrase: string, langCode: string): string => {
  if (!phrase || !langCode || langCode === 'en-IN' || langCode === 'en') return phrase;
  const trimmed = phrase.trim();
  if (PHRASE_GLOSSARY[trimmed] && PHRASE_GLOSSARY[trimmed][langCode]) {
    return PHRASE_GLOSSARY[trimmed][langCode];
  }
  return phrase;
};
